//go:build unit

package service

import (
	"strings"
	"testing"
)

// 第232轮实际回复的结论段：正文与不同条件下的补充答案必须分开。
const intelCheckRound232Conclusion = "因此20颗无论怎样分配形状，都不能保证成功，而21颗可以，故答案为 **21颗**。\n\n" +
	"注：如果不允许按手感选择形状、只能完全随机拿取，则答案是29颗；本题特意说明形状可凭手感分辨，因此应利用这一条件。"

func TestExtractIntelCheckAnswer_Context(t *testing.T) {
	tests := []struct {
		name, reply, expected string
	}{
		{"第232轮结论不被注释覆盖", intelCheckRound232Conclusion, "21"},
		{"反向注释不能洗成正确答案", "最终答案：29\n\n注：如果换一个条件，答案是21。", "29"},
		{"注释中的最终字样不提高优先级", "本题答案：17\n\n注：如果换一个条件，最终答案：25。", "17"},
		{"条件盒装不能覆盖正文", "本题答案：17\n\n注：如果换一个条件，答案为 \\boxed{25}。", "17"},
		{"同一行的另一条件", "本题最终答案：17。若改为另一种条件，答案是25。", "17"},
		{"多行注释继承条件语境", "最终答案：17\n\n注：\n如果换一个条件，\n最终答案：25。", "17"},
		{"注释标题后的段落", "最终答案：17\n\n### 注释\n\n如果改用另一种条件，答案是25。", "17"},
		{"英文条件注释", "The final answer: 17 items.\n\nNote: If a different assumption is used, the final answer: 25 items.", "17"},
		{"普通条件推理不是另一个答案", "如果按题意选择形状，就能保证配对。因此，最终答案：17。", "17"},
		{"正文重申本题条件", "注：如果换一个条件，答案是25。\n\n按题意，本题最终答案：17。", "17"},
		{"注释中的真正更正", "初步答案：29\n\n注：前面计算有误，更正后的最终答案：21。", "21"},
		{"更正覆盖旧盒装", "初算为 \\boxed{29}。\n\n注：更正后的最终答案：21。", "21"},
		{"英文更正", "The final answer: 25.\n\nNote: Correction: the final answer: 17.", "17"},
		{"补充更正后仍有假设讨论", "答案：29。\n\n补充：更正，最终答案：21。若改用另一条件，答案是35。", "21"},
		{"文本答案也保留正文", "本题最终答案：蓝色。\n\n注：如果换一种灯光，答案是红色。", "蓝色"},
		{"附注假设跨句保持", "正文最终答案：17。\n\n注：如果换一个条件，可以重新计算。\n因此最终答案：25。", "17"},
		{"附注假设后重新声明本题", "注：如果换一个条件，答案是25。按题意，本题最终答案：17。", "17"},
		{"另一个变量不代表换条件", "设另一个变量，最终答案：17。\n\n注：如果换一个条件，答案是25。", "17"},
		{"换一个变量不代表换条件", "换一个变量计算，最终答案：17。\n\n注：如果换一个条件，答案是25。", "17"},
		{"更正信号跨句保留", "最终答案：\\boxed{25}。\n\n注：更正：前面计算有误。\n最终答案：17。", "17"},
		{"条件附注跨空行", "本题最终答案：17。\n\n注：如果换一个条件，需要另算。\n\n最终答案：25。", "17"},
		{"条件附注跨空行反向", "本题最终答案：25。\n\n注：如果换一个条件，需要另算。\n\n最终答案：17。", "25"},
		{"跨空行后回到本题", "本题最终答案：25。\n\n注：如果换一个条件，需要另算。\n\n按题意，本题最终答案：17。", "17"},
		{"后续最终结论覆盖早期更正", "更正：答案21。\n\n经过再次验算，最终答案：29。", "29"},
		{"后续最终结论覆盖早期更正反向", "更正：答案29。\n\n经过再次验算，最终答案：21。", "21"},
		{"Markdown注释标签", "本题最终答案：17。\n\n**注**：如果允许重复使用，最终答案：25。", "17"},
		{"长附注不丢条件状态", "本题最终答案：17。\n\n注：如果允许重复使用，" + strings.Repeat("此处是条件讨论。", 300) + "最终答案：25。", "17"},
		{"长更正不丢声明状态", "最终答案：\\boxed{25}。\n\n注：更正：" + strings.Repeat("重新验算。", 300) + "最终答案：17。", "17"},
		{"无空行标题不污染前文", "# 最终答案\n答案：17。\n## 另一种条件\n最终答案：25。", "17"},
		{"后置说明不覆盖盒装", "\\boxed{21}\n\n以上即最终答案", "21"},
		{"独立标签不覆盖盒装", "最终答案\n\n\\boxed{21}", "21"},
		{"引导语后盒装", "先排除20。\n\n最终答案如下。\n\n\\boxed{21}", "21"},
		{"冒号换段后盒装", "先排除20。\n\n最终答案：\n\n\\boxed{21}", "21"},
		{"更正中复述本题条件", "初步答案：29。\n\n注：更正：如果按题意允许按手感选择形状，最终答案：21。", "21"},
		{"附带条件内更正不切回本题", "本题最终答案：17。\n\n注：如果换一个条件，答案是25。更正：该条件下最终答案：26。", "17"},
		{"条件跨段文本答案反向", "本题最终答案：红色。\n\n注：如果换一个条件，需要另算。\n\n最终答案：蓝色。", "红色"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if got := ExtractIntelCheckAnswer(tt.reply); got != tt.expected {
				t.Errorf("extracted=%q, want=%q", got, tt.expected)
			}
		})
	}
}
